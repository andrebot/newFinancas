import { defaultIconDimensions, getIconData } from '@iconify/utils';

// Builds the web kit's icon registry (OQ-126): the chosen Material Symbols
// glyphs and card-network logos, copied out of the Iconify collections into one
// TypeScript module, so the app bundles only what it uses and makes no
// third-party request at runtime.

/** An Iconify collection, as published in `@iconify-json/<set>/icons.json`. */
export type IconCollection = Parameters<typeof getIconData>[0];

/** One icon's SVG content and the size of its view box. */
export interface IconData { body: string; width: number; height: number }

/** The collections the registry is copied from. */
export interface IconSources { glyphs: IconCollection; logos: IconCollection }

/** What goes into the registry: glyph names and the logo for each network. */
export interface IconSelection {
  glyphs: readonly string[];
  logos: Readonly<Record<string, string>>;
}

// Material Symbols are drawn on a 24 × 24 grid; the Icon component relies on it.
const GLYPH_GRID = 24;

const HEADER = `// Generated by tools/icons (\`pnpm generate:icons\`, OQ-126). Do not edit:
// change tools/icons/src/selection.ts or CATEGORY_ICONS and regenerate.
// Glyphs: Material Symbols (Apache-2.0), 24 × 24. Logos: SVG Logos (CC0).
`;

/**
 * Looks an icon up in a collection, resolving aliases.
 *
 * @param collection - The Iconify collection.
 * @param name - The icon's name in it.
 * @returns The icon's body and view-box size.
 * @throws {Error} When the collection has no such icon.
 */
export const resolveIcon = (collection: IconCollection, name: string): IconData => {
  const icon = getIconData(collection, name);
  if (!icon) {
    throw new Error(`Unknown icon "${collection.prefix}:${name}"`);
  }

  // Iconify leaves out a size that equals its 16 × 16 default.
  const { body, width, height } = { ...defaultIconDimensions, ...icon };

  return { body, width, height };
};

/**
 * Collects the glyphs by name, each once, in name order.
 *
 * @param collection - The Material Symbols collection.
 * @param names - Glyph names; duplicates are fine.
 * @returns `[name, body]` pairs.
 * @throws {Error} On an unknown glyph or one not drawn on the 24 × 24 grid.
 */
export const collectGlyphs = (
  collection: IconCollection,
  names: readonly string[],
): [string, string][] => [...new Set(names)].sort().map((name) => {
  const icon = resolveIcon(collection, name);
  if (icon.width !== GLYPH_GRID || icon.height !== GLYPH_GRID) {
    const size = `${icon.width} × ${icon.height}`;
    throw new Error(`Icon "${name}" is ${size}, not ${GLYPH_GRID} × ${GLYPH_GRID}`);
  }

  return [name, icon.body];
});

/**
 * Collects each network's logo, keeping the logo's own view box.
 *
 * @param collection - The logos collection.
 * @param logos - Network code → logo name.
 * @returns `[network, icon]` pairs in the given order.
 * @throws {Error} On an unknown logo.
 */
export const collectLogos = (
  collection: IconCollection,
  logos: Readonly<Record<string, string>>,
): [string, IconData][] => Object.entries(logos).map(([network, name]) => (
  [network, resolveIcon(collection, name)]
));

/**
 * Renders the registry module's source.
 *
 * @param glyphs - `[name, body]` pairs.
 * @param logos - `[network, icon]` pairs.
 * @returns The TypeScript source of the generated module.
 */
export const renderModule = (
  glyphs: [string, string][],
  logos: [string, IconData][],
): string => {
  const quote = JSON.stringify;
  const glyphLines = glyphs.map(([name, body]) => `  ${quote(name)}: ${quote(body)},`);
  const logoLines = logos.map(([network, { width, height, body }]) => (
    `  ${quote(network)}: { width: ${width}, height: ${height}, body: ${quote(body)} },`
  ));

  return [
    HEADER,
    'export const GLYPHS = {', ...glyphLines, '};', '',
    'export type IconName = keyof typeof GLYPHS;', '',
    'export const CARD_NETWORK_LOGOS = {', ...logoLines, '};', '',
    'export type LogoNetwork = keyof typeof CARD_NETWORK_LOGOS;', '',
  ].join('\n');
};

/**
 * Builds the registry module from the collections and the selection.
 *
 * @param sources - The glyph and logo collections.
 * @param selection - Which glyphs and logos to include.
 * @returns The TypeScript source of the generated module.
 */
export const buildIconModule = (sources: IconSources, selection: IconSelection): string => (
  renderModule(
    collectGlyphs(sources.glyphs, selection.glyphs),
    collectLogos(sources.logos, selection.logos),
  )
);
