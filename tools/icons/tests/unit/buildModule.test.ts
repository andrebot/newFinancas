import { createRequire } from 'node:module';
import { CATEGORY_ICONS } from '@financas/reference';
import { describe, expect, it } from 'vitest';
import {
  buildIconModule, collectGlyphs, collectLogos, renderModule, resolveIcon,
  type IconCollection,
} from '../../src/buildModule';
import { CARD_NETWORK_LOGOS, UI_ICONS } from '../../src/selection';

const glyphs: IconCollection = {
  prefix: 'material-symbols',
  width: 24,
  height: 24,
  icons: {
    add: { body: '<path d="add"/>' },
    close: { body: '<path d="close"/>' },
    wide: { body: '<path d="wide"/>', width: 32 },
    tall: { body: '<path d="tall"/>', height: 32 },
  },
  aliases: { plus: { parent: 'add' } },
};

const logos: IconCollection = {
  prefix: 'logos',
  icons: {
    visa: { body: '<path d="visa"/>', width: 256, height: 83 },
    dinersclub: { body: '<path d="diners"/>', width: 512, height: 134 },
  },
};

describe('resolveIcon', () => {
  it('returns the body and the view box, with collection defaults', () => {
    expect(resolveIcon(glyphs, 'add'))
      .toEqual({ body: '<path d="add"/>', width: 24, height: 24 });
  });

  it('resolves an alias to its parent', () => {
    expect(resolveIcon(glyphs, 'plus').body).toBe('<path d="add"/>');
  });

  it('falls back to Iconify’s 16 × 16 when neither icon nor collection has a size', () => {
    const bare: IconCollection = { prefix: 'bare', icons: { dot: { body: '<circle/>' } } };

    expect(resolveIcon(bare, 'dot')).toEqual({ body: '<circle/>', width: 16, height: 16 });
  });

  it('names the collection and icon when the icon is unknown', () => {
    expect(() => resolveIcon(glyphs, 'nope')).toThrow('Unknown icon "material-symbols:nope"');
  });
});

describe('collectGlyphs', () => {
  it('keeps each name once, in name order', () => {
    expect(collectGlyphs(glyphs, ['close', 'add', 'close'])).toEqual([
      ['add', '<path d="add"/>'],
      ['close', '<path d="close"/>'],
    ]);
  });

  it.each(['wide', 'tall'])('rejects %s, which is off the 24 × 24 grid', (name) => {
    expect(() => collectGlyphs(glyphs, [name])).toThrow(`Icon "${name}" is`);
  });
});

describe('collectLogos', () => {
  it('maps each network to its logo, keeping the logo’s view box', () => {
    expect(collectLogos(logos, { visa: 'visa', diners: 'dinersclub' })).toEqual([
      ['visa', { body: '<path d="visa"/>', width: 256, height: 83 }],
      ['diners', { body: '<path d="diners"/>', width: 512, height: 134 }],
    ]);
  });
});

describe('renderModule', () => {
  it('writes the glyphs, the logos and their name types', () => {
    const source = renderModule(
      [['add', '<path d="a"/>']],
      [['visa', { body: '<g/>', width: 256, height: 83 }]],
    );

    expect(source).toContain('// Generated by tools/icons');
    expect(source).toContain('export const GLYPHS = {\n  "add": "<path d=\\"a\\"/>",\n};');
    expect(source).toContain('export type IconName = keyof typeof GLYPHS;');
    expect(source).toContain('export const CARD_NETWORK_LOGOS = {\n'
      + '  "visa": { width: 256, height: 83, body: "<g/>" },\n};');
    expect(source).toContain('export type LogoNetwork = keyof typeof CARD_NETWORK_LOGOS;');
  });
});

describe('buildIconModule', () => {
  it('renders the selected glyphs and logos', () => {
    const source = buildIconModule(
      { glyphs, logos },
      { glyphs: ['close', 'plus'], logos: { visa: 'visa' } },
    );

    expect(source).toContain('"close": "<path d=\\"close\\"/>"');
    expect(source).toContain('"plus": "<path d=\\"add\\"/>"');
    expect(source).toContain('"visa": { width: 256, height: 83');
  });

  it('resolves the real selection against the real collections', () => {
    const requireJson = createRequire(import.meta.url);
    const sources = {
      glyphs: requireJson('@iconify-json/material-symbols/icons.json') as IconCollection,
      logos: requireJson('@iconify-json/logos/icons.json') as IconCollection,
    };

    expect(() => buildIconModule(sources, {
      glyphs: [...UI_ICONS, ...CATEGORY_ICONS], logos: CARD_NETWORK_LOGOS,
    })).not.toThrow();
  });
});
